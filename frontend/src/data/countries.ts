export function getCountryEntry(code: string | null | undefined): CountryEntry | null {
  if (!code) return null;
  return byCode.get(code.trim().toUpperCase()) ?? null;
}

export function getCountryDisplayName(entry: CountryEntry, language: LanguageCode): string {
  if (language === 'he' && entry.nameHe) return entry.nameHe;
  if (language === 'ru' && entry.nameRu) return entry.nameRu;
  return entry.name;
}
